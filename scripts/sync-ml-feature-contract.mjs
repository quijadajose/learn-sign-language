#!/usr/bin/env node
/**
 * Sync ML feature constants from schemas/ml-feature-contract.json into
 * backend, frontend, and Python trainer source files.
 *
 * Usage (from repo root):
 *   node scripts/sync-ml-feature-contract.mjs
 *   node scripts/sync-ml-feature-contract.mjs --check   # CI: exit 1 if drift
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const checkOnly = process.argv.includes('--check');

const contractPath = path.join(root, 'schemas', 'ml-feature-contract.json');
const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'));
const p = contract.properties;

const values = {
  featuresCount: p.featuresCount.const,
  staticFeaturesCount: p.staticFeaturesCount.const,
  dynamicFeaturesCount: p.dynamicFeaturesCount.const,
  fixedDynamicSequenceLength: p.fixedDynamicSequenceLength.const,
  featuresSchemaStatic: p.featuresSchemaStatic.const,
  featuresSchemaDynamic: p.featuresSchemaDynamic.const,
  legacyFeaturesSchemaStatic: p.legacyFeaturesSchemaStatic.const,
  legacyFeaturesSchemaDynamic: p.legacyFeaturesSchemaDynamic.const,
  modelPoseLandmarks: p.modelPoseLandmarks.const,
  velocityPoseLandmarks: p.velocityPoseLandmarks.const,
};

const tsList = (items) =>
  `[${items.map((v) => (typeof v === 'string' ? `'${v}'` : v)).join(', ')}] as const`;

/** Python tuples need a trailing comma when they hold a single element. */
const pyTuple = (items) => {
  const body = items
    .map((v) => (typeof v === 'string' ? `"${v}"` : v))
    .join(', ');
  return items.length === 1 ? `(${body},)` : `(${body})`;
};

const tsContent = `/* AUTO-GENERATED by scripts/sync-ml-feature-contract.mjs — do not edit */
export const FEATURES_COUNT = ${values.featuresCount} as const;
export const STATIC_FEATURES_COUNT = ${values.staticFeaturesCount} as const;
export const DYNAMIC_FEATURES_COUNT = ${values.dynamicFeaturesCount} as const;
export const FIXED_DYNAMIC_SEQUENCE_LENGTH = ${values.fixedDynamicSequenceLength} as const;
export const FEATURES_SCHEMA_STATIC = '${values.featuresSchemaStatic}' as const;
export const FEATURES_SCHEMA_DYNAMIC = '${values.featuresSchemaDynamic}' as const;
export const LEGACY_FEATURES_SCHEMA_STATIC = ${tsList(values.legacyFeaturesSchemaStatic)};
export const LEGACY_FEATURES_SCHEMA_DYNAMIC = ${tsList(values.legacyFeaturesSchemaDynamic)};
export const MODEL_POSE_LANDMARKS = ${tsList(values.modelPoseLandmarks)};
export const VELOCITY_POSE_LANDMARKS = ${tsList(values.velocityPoseLandmarks)};
`;

const targets = [
  {
    file: path.join(
      root,
      'lsv-backend/src/sign-record/domain/utils/ml-feature-contract.generated.ts',
    ),
    content: tsContent,
  },
  {
    file: path.join(
      root,
      'lsv-frontend/src/utils/ml-feature-contract.generated.ts',
    ),
    content: tsContent,
  },
  {
    file: path.join(root, 'lsv-model-trainer/ml_feature_contract_generated.py'),
    content: `# AUTO-GENERATED by scripts/sync-ml-feature-contract.mjs — do not edit
FEATURES_COUNT = ${values.featuresCount}
STATIC_FEATURES_COUNT = ${values.staticFeaturesCount}
DYNAMIC_FEATURES_COUNT = ${values.dynamicFeaturesCount}
FIXED_SEQUENCE_LENGTH = ${values.fixedDynamicSequenceLength}
FEATURES_SCHEMA_STATIC = "${values.featuresSchemaStatic}"
FEATURES_SCHEMA_DYNAMIC = "${values.featuresSchemaDynamic}"
LEGACY_FEATURES_SCHEMA_STATIC = ${pyTuple(values.legacyFeaturesSchemaStatic)}
LEGACY_FEATURES_SCHEMA_DYNAMIC = ${pyTuple(values.legacyFeaturesSchemaDynamic)}
MODEL_POSE_LANDMARKS = ${pyTuple(values.modelPoseLandmarks)}
VELOCITY_POSE_LANDMARKS = ${pyTuple(values.velocityPoseLandmarks)}
`,
  },
];

let drifted = false;
for (const { file, content } of targets) {
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (existing === content) {
    console.log(`ok  ${path.relative(root, file)}`);
    continue;
  }
  drifted = true;
  if (checkOnly) {
    console.error(`drift ${path.relative(root, file)}`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`wrote ${path.relative(root, file)}`);
  }
}

if (checkOnly && drifted) {
  console.error(
    'ML feature contract drift detected. Run: node scripts/sync-ml-feature-contract.mjs',
  );
  process.exit(1);
}

console.log(
  checkOnly
    ? 'ML feature contract in sync.'
    : 'ML feature contract generated.',
);
